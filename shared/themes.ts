import { z } from "zod";

export const themeSchema = z.object({
  name: z.string(),
  variant: z.enum(["professional", "tint", "vibrant"]),
  primary: z.string(),
  appearance: z.enum(["light", "dark", "system"]),
  radius: z.number(),
  chat: z.object({
    bubbleStyle: z.enum(["modern", "classic", "minimal"]),
    userBubbleColor: z.string(),
    otherBubbleColor: z.string(),
    fontStyle: z.enum(["default", "rounded", "monospace"]),
    background: z.string(),
    textColor: z.string(),
    inputBackground: z.string(),
    inputBorder: z.string(),
    sidebarBackground: z.string(),
    sidebarText: z.string(),
    accentColor: z.string(),
    fontFamily: z.string().optional(),
    bubbleShadow: z.boolean().optional(),
    bubbleHoverEffect: z.boolean().optional(),
    containerClassName: z.string().optional(),
    scrollAreaClassName: z.string().optional(),
  }),
});

export type Theme = z.infer<typeof themeSchema>;

